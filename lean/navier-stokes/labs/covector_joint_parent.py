#!/usr/bin/env python3
"""Joint original-parent variance and complete unforced coframe rate tests.

All Fourier outputs are retained on the 2*pi torus. Finite joint frames
are checked independently with rational arithmetic; they are not a flow
existence theorem. Stochastic/time construction and a continuation bound
for the remaining forward-frame receiver cost are separate obligations.
"""

import json
import sympy as s
import pressure_history_source as f
import pressure_memory_diffusion as pm
from pressure_impulse_history import vector_transport, matrix_transport, vectors_equal
from signed_viscous_pressure import interacting_datum
from joint_coframe_pressure import require
from covector_fluid_bridge import vector_add, vector_scale, covector_rhs


def matrix_sub(a, b):
    return pm.matrix_add(a, pm.matrix_scale(-1, b))


def parent_rhs(nu, u, B, g):
    return vector_add(vector_transport(u, g, nu), f.matvec(B, g))


def actual_rates():
    u, nu = interacting_datum(), f.QQ_I(1)/10
    B = f.jac(u)
    p = f.tensor_pressure(f.tensor(u, u))
    gp = f.grad(p)
    u1 = vector_add(vector_transport(u, u, nu), vector_scale(-1, gp))
    B1 = f.jac(u1)
    gp1 = f.grad(f.tensor_pressure(pm.symmetric_product(u, u1)))
    u2 = vector_add(vector_transport(u, u1, nu), vector_scale(-1, [f.adv(u1, q) for q in u]),
                    vector_scale(-1, gp1))
    f.equal(pm.divergence(u1), {}, 'canonical physical first tangent remains solenoidal')
    f.equal(pm.divergence(u2), {}, 'canonical physical second tangent remains solenoidal')
    m1 = covector_rhs(nu, u, B, u)
    m2 = vector_add(covector_rhs(nu, u, B, m1), vector_scale(-1, [f.adv(u1, q) for q in u]),
                    vector_scale(-1, f.matvec(pm.transpose(B1), u)))
    Q1 = pm.matrix_add(B, pm.transpose(B))
    N1 = pm.matrix_scale(-1, Q1)
    N2 = pm.matrix_add(matrix_transport(u, N1, nu), pm.matrix_scale(-1, pm.transpose(B1)),
        pm.matrix_scale(-1, B1), pm.matrix_scale(-1, f.matmul(pm.transpose(B), N1)),
        pm.matrix_scale(-1, f.matmul(N1, B)))
    Q2 = pm.matrix_add(pm.matrix_scale(-1, N2), pm.matrix_scale(2, f.matmul(N1, N1)))
    a1 = vector_add(f.matvec(Q1, u), m1)
    a2 = vector_add(f.matvec(Q2, u), vector_scale(2, f.matvec(Q1, m1)), m2)
    g1 = parent_rhs(nu, u, B, u)
    g2 = vector_add(parent_rhs(nu, u, B, g1), vector_scale(-1, [f.adv(u1, q) for q in u]),
                    f.matvec(B1, u))
    vectors_equal(a1, [f.scale(nu, f.lap(q)) for q in u], 'actual normalized parent first rate')
    vectors_equal(g1, a1, 'original joint parent has the same initial rate')
    f.equal(pm.divergence(g1), {}, 'joint parent first tangent is solenoidal')
    f.equal(pm.divergence(g2), {}, 'joint parent second tangent is solenoidal')
    divergence2 = pm.divergence(a2)
    divergence_square = pm.mean(f.mul(divergence2, divergence2))
    require(divergence_square > 0, 'canonical moment quotient need not preserve incompressibility')

    # K_j=N_j Q retains all inverse-metric and mixed-diffusion terms.
    K1 = [pm.matrix_diff(N1, j) for j in range(3)]
    K2 = [pm.matrix_add(pm.matrix_diff(N2, j),
            pm.matrix_scale(2, f.matmul(K1[j], Q1))) for j in range(3)]
    for j in range(3):
        expected1 = pm.matrix_scale(-1, pm.matrix_diff(Q1, j))
        f.same_matrices(K1[j], expected1, ('complete initial connection rate', j))
        source2 = pm.matrix_add(f.matmul(K1[j], pm.transpose(B)),
            pm.matrix_scale(-1, f.matmul(pm.transpose(B), K1[j])),
            pm.matrix_scale(-1, pm.transpose(pm.matrix_diff(B1, j))),
            pm.matrix_scale(-1, f.matmul(N1, pm.matrix_diff(B, j))),
            pm.matrix_scale(-1, pm.matrix_diff(B1, j)),
            pm.matrix_scale(-1, f.matmul(pm.matrix_diff(B, j), Q1)),
            pm.matrix_scale(-1, pm.matrix_add(*(pm.matrix_scalar(B[k][j], K1[k])
                                               for k in range(3)))))
        lhs2 = pm.matrix_add(K2[j], pm.matrix_adv(u, K1[j]),
                              pm.matrix_scale(-nu, [[f.lap(v) for v in row] for row in K1[j]]))
        f.same_matrices(lhs2, source2, ('complete evolving connection rate retains pressure/drift', j))

    # D a=B a+2nu sum K_j^T partial_j a. The error against the
    # solenoidal original parent is generated by precisely this diffusion.
    error2 = vector_scale(2*nu, vector_add(*(f.matvec(pm.transpose(K1[j]),
                            [f.diff(v, j) for v in u]) for j in range(3))))
    vectors_equal(vector_add(a2, vector_scale(-1, g2)), error2,
                  'joint parent mismatch is generated by retained stochastic diffusion')
    f.equal(divergence2, pm.divergence(error2), 'all loss of auxiliary incompressibility stays in joint error')
    variance1 = f.scale(2*nu, pm.pair(B, B))
    require(pm.mean(variance1) > 0, 'original covector variance spends initial energy through diffusion')

    # A physical force enters the normalized parent as Q f and must
    # enter the original-data variance ledger; it is not free sampling.
    alpha = pm.mean(pm.pair(B, B))/pm.mean(f.dot(u, u))
    force = [f.add(f.scale(-1, f.lap(v)), f.scale(-f.QQ_I(alpha), v)) for v in u]
    require(pm.mean(f.dot(u, force)) == 0, 'fixed solenoidal force has zero initial kinetic work')
    f.equal(pm.divergence(force), {}, 'actual physical force remains solenoidal')
    vectors_equal(vector_add(f.matvec(Q1, u), m1, force), vector_add(a1, force),
                  'physical force survives in the canonical normalized-parent rate')
    return {'viscosity': str(nu.x), 'compressed_parent_divergence_second_jet_square': str(divergence_square),
            'retained_parent_divergence_first_and_second_jets': '0',
            'retained_variance_first_jet_mean': str(pm.mean(variance1)),
            'joint_error_second_jet_square': str(pm.mean(f.dot(error2, error2))),
            'failed_claim': 'the quotient of averaged covector and frame is always an incompressible parent',
            'scope': 'complete canonical unforced initial PDE jets; positive-time stochastic realization analytic',
            'force_scope': 'explicit initial solenoidal filter, not the imported singular trajectory'}


def strain_derivative_fixture():
    # These are the gradient derivatives of (y*z, z*x, x*y).
    return [s.Matrix([[0, 0, 0], [0, 0, 1], [0, 1, 0]]),
            s.Matrix([[0, 0, 1], [0, 0, 0], [1, 0, 0]]),
            s.Matrix([[0, 1, 0], [1, 0, 0], [0, 0, 0]])]


def mixed_local_rates():
    """Independent local matrix jets test the full nonzero diffusion terms.

    These supplied jets are not an actual stochastic NS realization.
    The separate canonical Fourier test supplies actual initial PDE jets.
    """
    nu = s.Rational(1, 10)
    N = s.Matrix([[2, 1, 0], [1, 3, 1], [0, 1, 2]])
    Q = N.inv()
    require(N.is_positive_definite, 'positive local coframe fixture')
    Nj = [s.Matrix([[1, 2, 0], [2, -1, 1], [0, 1, 1]]),
          s.Matrix([[0, 1, -1], [1, 2, 0], [-1, 0, 1]]),
          s.Matrix([[2, -1, 1], [-1, 0, 2], [1, 2, -2]])]
    P = s.Matrix([[1, 0, 1], [0, -1, 2], [1, 2, 0]])
    Njk = [[(j+1)*(k+1)*P for k in range(3)] for j in range(3)]
    B = s.Matrix([[1, 2, 3], [-3, 0, 1], [2, -1, -1]])
    Bj = strain_derivative_fixture()
    require(B.trace() == 0 and all(d.trace() == 0 for d in Bj), 'solenoidal drift jets')
    m = s.Matrix([1, -2, 3])
    mj = [s.Matrix([2, 1, -1]), s.Matrix([-1, 3, 1]), s.Matrix([1, -2, 4])]
    K = [d*Q for d in Nj]
    dK = [[Njk[j][k]*Q-K[j]*Nj[k]*Q for k in range(3)] for j in range(3)]
    dQ = [-Q*d*Q for d in Nj]
    DQ = B*Q+Q*B.T-2*nu*sum((Q*d*Q*d*Q for d in Nj), s.zeros(3))
    Dm = -B.T*m
    a = Q*m
    r = [d-K[j]*m for j, d in enumerate(mj)]
    da = [Q*v for v in r]
    Da = DQ*m+Q*Dm-2*nu*sum((dQ[k]*mj[k] for k in range(3)), s.zeros(3, 1))
    a_diffusion = 2*nu*sum((K[k].T*da[k] for k in range(3)), s.zeros(3, 1))
    require(Da == B*a+a_diffusion, 'complete normalized-parent rate with nonzero mixed diffusion')
    require(a_diffusion.dot(a_diffusion) > 0, 'normalized-parent mixed diffusion is exercised')
    connection_norms = []
    Dr = []
    receiver = sum((Bj[j].T*r[j] for j in range(3)), s.zeros(3, 1))
    for j in range(3):
        DNj = -Bj[j].T*N-B.T*Nj[j]-Nj[j]*B-N*Bj[j] \
            -sum((B[k, j]*Nj[k] for k in range(3)), s.zeros(3))
        DK = DNj*Q+Nj[j]*DQ-2*nu*sum((Njk[j][k]*dQ[k] for k in range(3)), s.zeros(3))
        k_diffusion = 2*nu*sum((dK[j][k]*K[k] for k in range(3)), s.zeros(3))
        expected_K = K[j]*B.T-B.T*K[j]-Bj[j].T-N*Bj[j]*Q \
            -sum((B[k, j]*K[k] for k in range(3)), s.zeros(3))+k_diffusion
        require(DK == expected_K, 'complete connection rate includes noncommuting mixed diffusion')
        connection_norms.append(s.trace(k_diffusion.T*k_diffusion))
        Dv = DK*m+K[j]*Dm-2*nu*sum((dK[j][k]*mj[k] for k in range(3)), s.zeros(3, 1))
        r_diffusion = 2*nu*sum((dK[j][k]*r[k] for k in range(3)), s.zeros(3, 1))
        expected_v = -B.T*K[j]*m-Bj[j].T*m-N*Bj[j]*a \
            -sum((B[k, j]*K[k]*m for k in range(3)), s.zeros(3, 1))-r_diffusion
        require(Dv == expected_v, 'connection-vector equation keeps every original parent')
        Dmj = -B.T*mj[j]-Bj[j].T*m \
            -sum((B[k, j]*mj[k] for k in range(3)), s.zeros(3, 1))
        expected_r = -B.T*r[j]-sum((B[k, j]*r[k] for k in range(3)), s.zeros(3, 1)) \
            +N*Bj[j]*a+r_diffusion
        require(Dmj-Dv == expected_r, 'full covariant-gradient source equation')
        Dr.append(Dmj-Dv)
    require(all(x > 0 for x in connection_norms), 'every connection mixed term is nonzero')
    source_work = sum(r[j].dot(Q*N*Bj[j]*a) for j in range(3))
    require(source_work == receiver.dot(a), 'inverse-metric source has the combined geometric receiver')
    # Independent spatial second covector jets test the complete F_m
    # product rule, rather than dropping the unpaid geometric terms.
    mjk = [[(j+1)*(k+1)*s.Matrix([1, -2, 0]) for k in range(3)] for j in range(3)]
    dr = [[mjk[j][k]-dK[j][k]*m-K[j]*mj[k] for k in range(3)] for j in range(3)]
    full_rate = sum(2*r[j].dot(Q*Dr[j])+r[j].dot(DQ*r[j]) for j in range(3)) \
        -2*nu*sum(dr[j][k].dot(Q*dr[j][k])+2*r[j].dot(dQ[k]*dr[j][k])
                   for j in range(3) for k in range(3))
    index_strain = -2*sum(B[k, j]*r[j].dot(Q*r[k]) for j in range(3) for k in range(3))
    mixed_connection = 4*nu*sum(r[j].dot(Q*dK[j][k]*r[k]) for j in range(3) for k in range(3))
    gradient_cost = sum((dr[j][k]-K[k]*r[j]).dot(Q*(dr[j][k]-K[k]*r[j]))
                        for j in range(3) for k in range(3))
    require(full_rate == index_strain+2*source_work+mixed_connection-2*nu*gradient_cost,
            'complete covariant-gradient production retains strain, parent, connection and diffusion')
    return {'connection_mixed_diffusion_squares': [str(x) for x in connection_norms],
            'normalized_parent_mixed_diffusion_square': str(a_diffusion.dot(a_diffusion)),
            'source_receiver': [str(x) for x in receiver],
            'full_covariant_gradient_production': str(full_rate),
            'scope': 'complete nonzero local rate algebra on supplied jets, not a fluid realization'}


def finite_joint_payment():
    weights = [s.Rational(1, 3), s.Rational(1, 6), s.Rational(1, 2)]
    frames = [s.Matrix([[1, 2, 0], [0, 1, 1], [0, 0, 1]]),
              s.Matrix([[1, 0, 1], [-2, 1, 0], [0, 0, 1]]),
              s.Matrix([[2, 1, 0], [0, s.Rational(1, 2), 0], [0, 0, 1]])]
    terminal = [s.Matrix([1, 2, -1]), s.Matrix([-2, 1, 3]), s.Matrix([3, -1, 2])]
    inverses = [F.inv() for F in frames]
    require(sum(weights) == 1 and all(w > 0 for w in weights), 'normalized joint law')
    require(all(F.det() == 1 for F in frames), 'compatible incompressible frame fixtures')
    N = sum((w*F.T*F for w, F in zip(weights, frames)), s.zeros(3))
    M = sum((w*J*J.T for w, J in zip(weights, inverses)), s.zeros(3))
    m = sum((w*F.T*v for w, F, v in zip(weights, frames, terminal)), s.zeros(3, 1))
    g = sum((w*J*v for w, J, v in zip(weights, inverses, terminal)), s.zeros(3, 1))
    a = N.inv()*m
    energy = sum(w*(v.dot(v)) for w, v in zip(weights, terminal))
    residuals = [v-F*a for v, F in zip(terminal, frames)]
    variance = sum(w*e.dot(e) for w, e in zip(weights, residuals))
    require(variance == energy-m.dot(a) and variance > 0, 'joint variance is original energy deficit')
    delta = g-a
    require(delta == sum((w*J*e for w, J, e in zip(weights, inverses, residuals)), s.zeros(3, 1)),
            'exact joint mismatch preserves frame and terminal choices')
    require(delta.dot(delta) > 0, 'quotient and retained parent differ')
    z = s.Matrix([2, -3, 1])
    cost = z.dot(M*z)
    require(delta.dot(z)**2 <= cost*variance, 'forward-metric receiver square paid by joint variance')
    for t in (-2, -1, 0, s.Rational(1, 3), 1, 2):
        completed = sum(w*(e-t*J.T*z).dot(e-t*J.T*z)
                        for w, J, e in zip(weights, inverses, residuals))
        require(completed == variance-2*t*z.dot(delta)+t*t*cost and completed >= 0,
                'complete signed receiver transfer with explicit remaining cost')
    dB = strain_derivative_fixture()
    r = [s.Matrix([1, 2, -1]), s.Matrix([-2, 1, 3]), s.Matrix([3, -1, 2])]
    source_receiver = sum((dB[j].T*r[j] for j in range(3)), s.zeros(3, 1))
    source_a = sum(r[j].dot(dB[j]*a) for j in range(3))
    source_g = sum(r[j].dot(dB[j]*g) for j in range(3))
    source_cost = source_receiver.dot(M*source_receiver)
    require(source_receiver.dot(delta) == source_g-source_a, 'joint geometric parent-source reconstruction')
    require(2*source_a <= 2*source_g+variance+source_cost, 'one variance pays the combined parent-source error')
    # A compressed snapshot must not replace joint choices. Permuting
    # only terminal parents changes the true covector and its deficit.
    permuted = terminal[1:]+terminal[:1]
    permuted_m = sum((w*F.T*v for w, F, v in zip(weights, frames, permuted)), s.zeros(3, 1))
    require(permuted_m != m, 'joint frame-parent relation is part of the boundary history')
    return {'terminal_energy': str(energy), 'normalized_energy': str(m.dot(a)),
            'joint_variance': str(variance), 'parent_mismatch_square': str(delta.dot(delta)),
            'signed_receiver_work': str(2*z.dot(delta)), 'forward_frame_receiver_cost': str(cost),
            'geometric_source_work': str(2*source_a), 'retained_parent_source_work': str(2*source_g),
            'geometric_receiver_cost': str(source_cost),
            'scope': 'exact finite joint samples, not an NS flow or a continuation bound'}


