"""Pressure pairing and transported transversality of viscous memory.

All Fourier products retain every mode. Taylor--Green velocities below
are complete exact unforced evolutions, not Galerkin trajectories. Their
memory is defined by its actual parabolic equation; its first two time
derivatives certify pressure generation, not a uniform Taylor window.
The accompanying README states the general weighted pairing estimate
and the unpaid receiver norm. Requires SymPy and neighboring labs.
"""
import json
