def divergence(matrix):
    return [f.add(*(f.diff(matrix[i][j],j) for j in range(3))) for i in range(3)]


def average(field):
    return d.ev({f.ORIGIN:field.get(f.ORIGIN,f.ZERO)})


def at(field,phases,n=1):
    value=f.ZERO
    for k,a in field.items():
        if any(ki % n for ki in k):raise ArithmeticError('frequency lattice')
        for ki,phase in zip(k,phases):a*=phase**(ki//n)
        value+=a
    return d.ev({f.ORIGIN:value})


def mat_at(matrix,phases,n=1):
    return s.Matrix([[at(a,phases,n) for a in row] for row in matrix])


def taylor_green(n,beta):
    sx=d.sin((n,0,0));cx=d.cos((n,0,0))
    sy=d.sin((0,n,0));cy=d.cos((0,n,0))
    return [f.mul(sx,cy),f.scale(-1,f.mul(cx,sy)),f.scale(beta,f.mul(sx,sy))]


def check_taylor_green(n,beta):
    nu=f.QQ_I(1)/5;ns=s.Rational(1,5)
    u=taylor_green(n,beta);B=f.jac(u);p=f.tensor_pressure(f.tensor(u,u))
    f.equal(f.trace(B),{},'actual solenoidal Taylor--Green datum')
    for a in u:f.equal(f.lap(a),f.scale(-2*n*n,a),'single Laplace eigenvalue')
    expected_p=f.scale(f.QQ_I(1)/4,f.add(d.cos((2*n,0,0)),d.cos((0,2*n,0))))
    f.equal(p,expected_p,'canonical pressure, including the passive third component')

    # This identity holds for symbolic q=exp(-2nu*n^2*t), at every time.
    # The third component is a multiple of the streamfunction, hence
    # advected without changing the exact heat-decaying solution.
    ring=f.QQ_I.poly_ring('q');q=ring.gens[0]
    uq=[f.scale(q,a) for a in u];pq=f.tensor_pressure(f.tensor(uq,uq))
    for i,a in enumerate(uq):
        rhs=f.add(f.scale(nu,f.lap(a)),f.scale(-1,f.adv(uq,a)),f.scale(-1,f.diff(pq,i)))
        f.equal(rhs,f.scale(-2*nu*n*n,a),'complete all-time unforced NS equation')

    G=f.matmul(B,[list(row) for row in zip(*B)])
    for a in divergence(G):f.equal(a,{},'the memory source is tensor-divergence free')
    f.equal(f.tensor_pressure(G),{},'the initial source has zero pressure')
    Gt=[[f.scale(-4*nu*n*n,a) for a in row] for row in G]
    C1=[[f.scale(2*nu,a) for a in row] for row in G]
    C2=[[f.add(f.scale(nu,f.lap(C1[i][j])),f.scale(-1,f.adv(u,C1[i][j])),
                f.scale(2*nu,Gt[i][j])) for j in range(3)] for i in range(3)]
    p1=f.tensor_pressure(C1);p2=f.tensor_pressure(C2)
    f.equal(p1,{},'zero first memory-pressure time derivative')
    expected_p2=f.scale(2*nu*n**3/5,f.add(
        f.mul(d.cos((3*n,0,0)),d.cos((0,n,0))),
        f.scale(-1,f.mul(d.cos((n,0,0)),d.cos((0,3*n,0))))))
    f.equal(p2,expected_p2,'nonzero memory pressure generated by actual transport')
    if not p2:raise ArithmeticError('the transport defect must be nonzero')

    # Differentiate the exact divergence equation once from C(0)=0.
    # The source divergence is zero here, so only transport remains.
    h2=divergence(C2)
    for i in range(3):
        expected=f.scale(-1,f.add(*(f.mul(B[k][j],f.diff(C1[i][j],k))
                                    for j in range(3) for k in range(3))))
        f.equal(h2[i],expected,'actual divergence-memory commutator')

    if beta==0:
        f.equal(G[0][0],G[1][1],'constant simultaneous memory eigenframe')
        for a in G[2]+[row[2] for row in G]:f.equal(a,{},'planar memory block')
        # Uniqueness of the scalar parabolic problems preserves these
        # linear relations for C at all times, not just at the initial jet.

    phase=f.QQ_I(3,4)/5
    phases=(phase,phase,f.QQ_I(1)) if beta==0 else (f.QQ_I(1),phase,f.QQ_I(1))
    b=mat_at(B,phases,n);strain=(b+b.T)/2
    w=s.Matrix([at(a,phases,n) for a in f.curl(u)])
    pressure=mat_at(f.hess(p),phases,n);P2=mat_at(f.hess(p2),phases,n)
    W=w.dot(w);V=w.dot(strain*w);Q=s.trace(strain*strain)
    Z=(strain*w).dot(strain*w);N=w.dot(pressure*w)
    gap=-2*N-s.Rational(4,7)*Z-s.Rational(10,21)*Q*W+W**2/5
    # The direct -K*C strain reaction in the actual pressure/core reserve.
    # C=P_C=P_C,t=0 initially, so its second time coefficient uses these
    # initial weights and P_C,tt. No derivatives of the weight are omitted.
    first=s.factor(10*V/(W+1)*w.dot(P2*w))
    bracket=s.factor(s.Rational(8,7)*(strain*w).dot(P2*w)
                     +s.Rational(20,21)*W*s.trace(strain*P2))
    if beta==0:
        d.zero(first,'planar vorticity annihilates the first pressure contraction')
        if bracket<=0:raise ArithmeticError('positive direct memory reaction')
        # 1-theta >= 1/[2(|gap|+1)(2|gap|+1)] for delta=1.
        lower=s.factor(bracket/(2*(abs(gap)+1)*(2*abs(gap)+1)))
    else:
        if first<=0 or bracket<0:raise ArithmeticError('positive three-component memory reaction')
        lower=first
        d.zero(w.dot(P2*w)+s.Rational(36096,15625)*ns*n**7,
               'nonzero actual vorticity-pressure memory coupling')
    if lower<=0:raise ArithmeticError('strict rational lower certificate')
    return {'frequency':n,'third_component':beta,'viscosity':'1/5',
            'initial_mean_energy':str(average(f.dot(u,u))),
            'source_pressure':'0','memory_pressure_first_time_derivative':'0',
            'memory_pressure_second_time_derivative':
                '2*nu*n^3/5 * [cos(3nx)cos(ny)-cos(nx)cos(3ny)]',
            'constant_memory_eigenframe_for_all_times':beta==0,
            'reserve_gap_at_receiver':str(gap),
            'direct_memory_second_time_coefficient_first_part':str(first),
            'direct_memory_second_time_coefficient_switch_part':str(bracket),
            'strict_rational_lower_certificate':str(lower),
            'scope':'a regular exact unforced flow and its actual initial memory jet; '
                    'no arbitrary-history or uniform Taylor-window claim'}


def check_pairing():
    u=f.fixture();C=f.tensor(u,u)
    for i in range(3):C[i][i]=f.add(C[i][i],d.ONE)
    p=f.tensor_pressure(C);P=f.hess(p);h=divergence(C)
    left=average(f.add(*(f.mul(C[i][j],P[i][j]) for i in range(3) for j in range(3))))
    right=-average(f.dot(h,f.grad(p)))
    energy=average(f.dot(f.grad(p),f.grad(p)))
    d.zero(left-right,'pressure-Hessian pairing moves one derivative to the receiver')
    d.zero(left-energy,'self-pairing sign and pressure conventions')
    if left<=0:raise ArithmeticError('nonzero pressure pairing')

    # Kinematic positive stress tests the universal pointwise estimate.
    # It is not asserted to be a realized value of retained NS memory.
    c=d.matval(C);H=s.eye(3)+c;inv=H.inv()
    derivatives=[d.matval([[f.diff(a,j) for a in row] for row in C]) for j in range(3)]
    F=sum(s.trace(inv*a*inv*a) for a in derivatives)
    hh=s.Matrix([d.ev(a) for a in h]);v=s.Matrix([d.ev(a) for a in f.grad(p)])
    mass=s.trace(H);cost=mass*v.dot(H*v)
    if hh.dot(inv*hh)>mass*F or hh.dot(v)**2>F*cost:
        raise ArithmeticError('weighted divergence and receiver bounds')

    # A source vector partial_x u is solenoidal at birth. Componentwise
    # passive transport produces the displayed divergence commutator.
    U=taylor_green(1,1);v0=[f.diff(a,0) for a in U]
    f.equal(f.trace(f.jac(v0)),{},'solenoidal parent at birth')
    transported=[f.adv(U,a) for a in v0]
    comm=f.add(*(f.mul(f.diff(U[j],i),f.diff(v0[i],j))
                 for i in range(3) for j in range(3)))
    f.equal(f.trace(f.jac(transported)),comm,'passive-parent divergence defect')
    if not comm:raise ArithmeticError('transport must create the parent defect')
    return {'pressure_pairing_and_pointwise_bounds':'exactly verified',
            'passive_parent_defect':'nonzero despite incompressible fluid',
            'scope':'kinematic pairing identity and exact parent transport; '
                    'the weighted receiver norm is not bounded here'}


def check_rank_one():
    eta,b=s.symbols('eta b',positive=True)
    r1,r2,r3,t1,t2,t3=s.symbols('r1 r2 r3 t1 t2 t3',real=True)
    db=s.Matrix(s.symbols('b1 b2 b3',real=True));e=s.Matrix([1,0,0])
    Da=s.Matrix([[0,0,0],[r1,r2,r3],[t1,t2,t3]])
    Cj=[2*b*db[j]*(e*e.T)+b*b*(Da[:,j]*e.T+e*Da[:,j].T) for j in range(3)]
    h=sum((Cj[j][:,j] for j in range(3)),s.zeros(3,1))
    delta=db[0]+b*s.trace(Da)
    geometric=b*b*(Da*e-s.trace(Da)*e)
    for entry in h-geometric-2*b*delta*e:d.zero(entry,'rank-one exact divergence decomposition')
    inverse=s.diag(1/(eta+b*b),1/eta,1/eta)
    F=sum(s.trace(inverse*a*inverse*a) for a in Cj)
    angular=sum(a*a for a in Da)
    d.zero(F-4*b*b*db.dot(db)/(eta+b*b)**2
             -2*b**4*angular/(eta*(eta+b*b)),'rank-one entropy amplitude and orientation costs')
    remainder=b**4*(r1*r1+t1*t1+(r2-t3)**2+2*r3*r3+2*t2*t2)
    d.zero(2*b**4*angular-geometric.dot(geometric)-remainder,
           'sharp constant-two geometric sum-of-squares certificate')
    d.zero(4*b**4*angular+8*b*b*delta**2-h.dot(h)
           -(2*remainder+(geometric-2*b*delta*e).dot(geometric-2*b*delta*e)),
           'rank-one geometric-plus-solenoidality-defect certificate')


def check_point_receiver():
    # The receiver norm in the proved weak bound is not automatically
    # finite for point observations. Check the simplest endpoint limit:
    # C=0, H=eta I, M=rho_s I and q_M=-rho_s in whole space.
    x=s.symbols('x',real=True);sigma=s.symbols('sigma',positive=True)
    heat=s.exp(-x*x/(4*sigma))/s.sqrt(4*s.pi*sigma)
    one_mass=s.integrate(heat**2,(x,-s.oo,s.oo))
    one_gradient=s.integrate(s.diff(heat,x)**2,(x,-s.oo,s.oo))
    gradient=s.simplify(3*one_gradient*one_mass**2)
    d.zero(gradient-s.Rational(3,4)/sigma/(8*s.pi*sigma)**s.Rational(3,2),
           'three-dimensional heat receiver gradient norm')
    eps,T,nu,eta=s.symbols('eps T nu eta',positive=True)
    coefficient=s.simplify(3*eta**2*gradient.subs(sigma,nu))
    integral=coefficient*s.Rational(2,3)*(eps**(-s.Rational(3,2))-T**(-s.Rational(3,2)))
    d.zero(s.diff(integral,eps)+coefficient*eps**(-s.Rational(5,2)),
           'exact singular endpoint integral')
    if s.limit(integral,eps,0,dir='+')!=s.oo:
        raise ArithmeticError('point-receiver endpoint cost must diverge')
    # Gaussian isotropy gives the angular multiplier for every constant
    # symmetric receiver A, including nonzero trace-free ones.
    xx=s.Matrix(s.symbols('X Y Z',real=True))
    aa=s.symbols('a0:6',real=True)
    A=s.Matrix([[aa[0],aa[3],aa[4]],[aa[3],aa[1],aa[5]],[aa[4],aa[5],aa[2]]])
    moments={j:s.integrate(x**j*s.exp(-x*x/2)/s.sqrt(2*s.pi),(x,-s.oo,s.oo))
             for j in range(5)}
    gaussian=sum(coefficient*s.prod(moments[j] for j in powers)
                 for powers,coefficient in s.Poly(xx.dot(A*xx)**2,*xx).terms())
    d.zero(gaussian-s.trace(A)**2-2*s.trace(A*A),'constant receiver angular multiplier')
    return {'receiver':'M=rho_s I, zero memory',
            'squared_gradient_norm':'3/(4*nu*s) * (8*pi*nu*s)^(-3/2)',
            'constant_symmetric_receiver_factor':'[(tr A)^2+2tr(A^2)]/15',
            'time_integrated_receiver_cost_at_zero':'infinite',
            'scope':'failure of the unsmoothed dual-norm substitution, '
                    'not divergent actual pressure work or NS dynamics'}


