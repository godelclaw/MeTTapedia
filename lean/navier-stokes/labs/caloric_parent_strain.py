#!/usr/bin/env python3
"""Whole-time strain payment for the original caloric parent history.

Exact checks cover Fourier constants, the two heat integrations, physical
initial resources, scaling, and the conditional continuation multiplier.
Fourier/integral inequalities and actual-flow identification are analytic.
"""

import json
import sympy as s
from rotational_curl_reserve import require, zero


def potential_constant():
    radius,a,F,G=s.symbols('radius a F G',positive=True)
    area=8*s.pi**2/3
    integral=area*s.integrate(1/(a*a+radius*radius),(radius,0,s.oo))
    zero(integral-4*s.pi**3/(3*a), 'five-dimensional Fourier Cauchy integral')
    factor=s.simplify(integral/(2*s.pi)**5)
    zero(factor-1/(24*s.pi**2*a), 'unitary Fourier normalization')
    square=factor*(a*a*F*F+G*G)
    zero(square.subs(a,G/F)-F*G/(12*s.pi**2), 'optimized potential observation')
    cp=1/(2*s.sqrt(3)*s.pi)
    zero(cp**2-1/(12*s.pi**2), 'homogeneous observation constant')
    return cp


def heat_clock():
    nu,t,k=s.symbols('nu t k',positive=True)
    zero(s.integrate(s.exp(-nu*t*k*k),(t,0,s.oo))-1/(nu*k*k),
         'integrating the heat multiplier gives the potential observation')


def physical_resources():
    r=s.symbols('r',positive=True)
    b,br,bz=s.symbols('b b_r b_z',real=True)
    # The 4*r*b^2+4*r^2*b*b_r difference is d_r(2*r^2*b^2).
    zero(r*((r*bz)**2+(2*b+r*br)**2)-r**3*(br**2+bz**2)
         -(4*r*b*b+4*r*r*b*br), 'physical initial swirl enstrophy identity')
    lam,F,G,d=s.symbols('lambda F G d',positive=True)
    Fl=F*lam**(-s.Rational(1,2))
    Gl=G*lam**s.Rational(1,2)
    spatial=Fl*s.sqrt(Gl*((d*lam)*Fl+2*Gl))
    zero(spatial-F*s.sqrt(G*(d*F+2*G)),
         'the prepared-parent allowance is scale invariant when the cutoff scales')
    zero((Fl*s.sqrt(Gl*(d*Fl+2*Gl)))**2-F*F*G*(d*F/lam+2*G),
         'the fixed-cutoff term has a different scaling law')


def certificate():
    p=s.Rational(5,2)
    zero((p-1)*s.Rational(12,5)-s.Rational(18,5),
         'the continuation multiplier includes both the moment and diffusion losses')
    zero(s.Rational(25,16)*s.Rational(8,15)-s.Rational(5,6),
         'the critical-clock coefficient after half-diffusion absorption')
    cp=potential_constant()
    coefficient=s.simplify(2*cp**2)
    zero(coefficient-1/(6*s.pi**2), 'prepared-parent strain allowance')
    require(coefficient.is_positive, 'positive universal coefficient')
    return {
        'initial_resources':'F=||b0||_2(R5), G=||grad b0||_2(R5), d=||grad beta||_infinity',
        'physical_identification':'F^2=pi E_swirl(0), G^2=pi Z_swirl(0); E has no factor 1/2',
        'potential_estimate':'(2pi)^(-5/2) integral |fhat(xi)|/|xi|^2 <= (1/(2sqrt(3)pi))*sqrt(||f||_2 ||grad f||_2)',
        'parent_strain':'integral_0^infinity ||q1(t)||_infinity dt <= A_cal',
        'heat_clock':'integral_0^infinity ||B(t)||_infinity dt <= sqrt(F G)/(2sqrt(3)pi nu)',
        'A_cal':'F*sqrt(G*(d*F+2G))/(6pi^2 nu^2)',
        'no_cutoff':'when beta=1: A_cal=sqrt(2)*sqrt(E_swirl(0)*Z_swirl(0))/(6pi nu^2)',
        'no_reset':'q1 is generated by the original B(t)=heat(nu*t)b0, with the original beta and source history',
        'weight':'W=exp[-(3/2)integral_0^t (||q_paid||_infinity+||q1||_infinity)]',
        'funded_parent_bound':'W >= exp[-(3/2)(2 M_H+A_cal)]',
        'only_unpaid_parent':'qR=T integral_0^t heat(nu*(t-s))[partial_z(beta*(b^2-B^2))-v.grad eta_core] ds',
        'remaining_target':'integral_0^T W[(3/2)<qR,|b|^(5/2)>-(15nu/8)Dcrit] <= K_R(u0,nu,H,rho)',
        'conditional_continuation':'integral_0^T S^2 <= (5 C5/(6nu))*exp[(18/5)(2 M_H+A_cal)]*(M0+K_R)^(12/5)',
        'scope':'all original caloric-parent work against the ACTUAL evolving receiver is paid; source deformation and full nonlinear parent transport remain open',
        'cutoff':'exact covariance uses beta_lambda(x)=beta(lambda*x), or beta=1; at a fixed physical cutoff F^2*G*(d*F+2G) becomes F^2*G*(d*F/lambda+2G)',
    }


if __name__=='__main__':
    heat_clock()
    physical_resources()
    print(json.dumps(certificate(),indent=2))
