#!/usr/bin/env python3
"""Exhaustive Kauffman-completability check over all 3-connected planar cubic graphs of a
given order (generated by plantri -a -d -c3), reusing kauffman_completability_lab.py.

Usage: kauffman_completability_exhaustive.py PLANTRI N [--c2]
Outcome per order: graphs, trails, Kempe classes, classes with no completable state.
"""
import sys, subprocess, json, os
import networkx as nx
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, 'kauffman_completability_lab.py')).read().split('results = {')[0]
src = src.replace("NMAX = int(sys.argv[1]) if len(sys.argv) > 1 else 12", "NMAX = 0").replace(
    "SAMPLES = int(sys.argv[2]) if len(sys.argv) > 2 else 400", "SAMPLES = 0")
exec(src)
plantri, N = sys.argv[1], int(sys.argv[2])
conn = '-c2' if '--c2' in sys.argv else '-c3'
out = subprocess.run([plantri, '-a', '-d', conn, str(N)], capture_output=True, text=True)
graphs = []
for line in out.stdout.strip().split('\n'):
    if not line.strip(): continue
    head, body = line.split(' ', 1)
    G = nx.Graph()
    for i, adj in enumerate(body.split(',')):
        for ch in adj.strip():
            j = ord(ch) - ord('a')
            if i < j: G.add_edge(i, j)
    graphs.append(G)
trails = classes_n = bad = 0; viol = []
for gi, G in enumerate(graphs):
    for e in list(G.edges()):
        v1, v2 = e
        H = G.copy(); H.remove_edge(v1, v2)
        edges, inc, sts = states(H, v1, v2)
        if not sts: continue
        trails += 1
        for cls in kempe_class_check(edges, inc, sts, v1, v2):
            classes_n += 1
            if not any(completable(edges, c, v1, v2) for c in cls):
                bad += 1; viol.append({"graph": gi, "edges": [list(x) for x in G.edges()], "e": [v1, v2], "class_size": len(cls)})
print(f"order {N} {conn}: graphs {len(graphs)} trails {trails} classes {classes_n} violating {bad}", flush=True)
json.dump({"order": N, "conn": conn, "graphs": len(graphs), "trails": trails, "classes": classes_n, "violating": bad, "violations": viol},
          open(os.path.join(here, f"kauffman_exhaustive_{conn[1:]}_n{N}.json"), "w"), indent=1)
