#!/usr/bin/env python3
"""Generate untrusted complete D3009 repair records and input coverage.

The kernel checker validates decoded records, whole-chord answers, descent
and input coverage. Discovery chooses the smallest active interface that
supports repair. Packed numeric blocks keep the finite table representation
compact; no generated fact is trusted without its Lean check.
"""
import argparse
from collections import Counter
from functools import lru_cache
import hashlib
import json
import math
import re
from pathlib import Path
import time

from generate_exceptional_repair import PERMS, boundary, canonical, code, lean_blocks, pairings, permute
from generate_wheel_seed_repair import masks_for, rank_states
from probe_wheel_repair import SOURCE_REVISION, SOURCE_SHA256, wheel, witness


@lru_cache(None)
def skeleton_masks(count):
    ps = sorted(pairings(count), key=lambda ps:
                tuple(any(a == k for a, _ in ps) for k in range(count)))
    return tuple(tuple(masks_for(p)) for p in ps)


def choose(word, rank, ranks, index):
    for fixed in sorted((1, 2, 3), key=lambda c: (-word.count(c), c)):
        p = next(p for p in PERMS if p[fixed-1] == 1)
        oriented = permute(word, p)
        slots = [i for i,c in enumerate(oriented) if c != 1]
        rows = []
        for masks in skeleton_masks(len(slots)):
            for mask in masks:
                changed = list(oriented)
                for k, slot in enumerate(slots):
                    if mask >> k & 1:
                        changed[slot] ^= 1
                j = index[canonical(changed)]
                if ranks[j] < rank:
                    rows.append((mask, j, tuple(changed)))
                    break
            else:
                break
        else:
            return oriented, rows
    raise ValueError('no lower-ranked joint repair')


def packed_blocks(name, data, block):
    text = lean_blocks(name, data, block)
    def literal(match):
        return str(sum(int(c, 36) << (6*j) for j, c in enumerate(match[1])))
    return re.sub(r'"([0-9A-Z]*)"', literal, text).replace(': String :=', ': Nat :=')


def generate(args):
    started = time.monotonic()
    outer, center, rim, edges = wheel(7)
    words, ranks, stages = rank_states(args.cache)
    index = {w:i for i,w in enumerate(words)}
    records, orientations = [], []
    chosen = []
    active = Counter()
    samples = {}
    for i,(word,rank) in enumerate(zip(words,ranks)):
        if rank == 0:
            z, colors = witness(word,outer)
            full = dict(enumerate(boundary(word))) | {center:z} | dict(zip(rim,colors))
            assert all(full[a] != full[b] for a,b in edges)
            core = tuple(full[v] for v in range(13,21))
            oriented, rows = word, []
        else:
            core = ()
            oriented, rows = choose(word,rank,ranks,index)
            count = sum(c != 1 for c in oriented)
            active[count] += 1
            samples.setdefault((rank,count),i)
        orientations.append(oriented)
        records.append(''.join(map(str,oriented))+code(rank)+
                       ''.join(map(str,core)).ljust(8,'0')+code(len(chosen),5))
        assert len(records[-1]) == 27
        chosen.extend(rows)
        if i % 4096 == 0:
            print('records',i,'answers',len(chosen),'seconds',round(time.monotonic()-started,1),flush=True)
    encoded = []
    for mask,j,changed in chosen:
        p = next(p for p in PERMS if permute(changed,p) == orientations[j])
        encoded.append(code(mask,3)+code(j,4)+code(PERMS.index(p)))
    lookup=[]
    for j in range(3**12):
        partial = tuple(1+(j//3**k)%3 for k in range(12))
        last=0
        for c in partial:last ^= c
        if last == 0:
            lookup.append('00000')
            continue
        word=partial+(last,)
        i=index[canonical(word)]
        p=next(p for p in PERMS if permute(word,p)==orientations[i])
        lookup.append(code(i,4)+code(PERMS.index(p)))
    shared_records, actions, selectors = [], [], []
    for i,row in enumerate(records):
        start = int(row[22:27],36)
        stop = int(records[i+1][22:27],36) if i+1<len(records) else len(encoded)
        local = {}
        record = row[:22]+code(len(actions),5)
        selection_start = len(selectors)
        for action in encoded[start:stop]:
            if action not in local:
                local[action] = len(local)
                actions.append(action)
            selectors.append(code(local[action],2))
        record += code(len(local),2)+code(selection_start,5)
        assert len(record)==34
        shared_records.append(record)
    print('encoding',len(records),'actions',len(actions),'selections',len(selectors),'inputs',len(lookup),flush=True)
    text='''/-!
# Complete D3009 repair data with shared actions

Generated by tools/fourcolor/near-linear/generate_wheel_repair.py.
Flat packed numbers are untrusted certificates. Separate kernel checks must
establish source colouring, joint chord coverage, rank descent and coverage
of every proper thirteen-port input. Each digit occupies six bits; the
semantic checker validates all decoded observations. Catalogue and licence:
tools/fourcolor/near-linear.
-/
namespace FourColor.WheelRepairData

'''
    text+=f'def count : Nat := {len(records)}\ndef block : Nat := {args.block}\ndef selectionBlock : Nat := {4*args.block}\n\n'
    for name,data,block in [('records',shared_records,args.block),('actions',actions,args.block),
                            ('selections',selectors,4*args.block),('lookup',lookup,args.block)]:
        text+=packed_blocks(name,data,block)
    text+='end FourColor.WheelRepairData\n'
    args.output.write_text(text)
    report=dict(status='untrusted complete certificate; requires kernel checks',source_sha256=SOURCE_SHA256,
        source_revision=SOURCE_REVISION,states=len(records),terminals=stages[0],stages=stages,
        active_counts=dict(sorted(active.items())),answers=len(encoded),lookup_entries=len(lookup),
        three_chord_answers=sum(mask.bit_count()==6 for mask,_,_ in chosen),
        block=args.block,selection_block=4*args.block,record_width=34,action_width=8,input_width=5,
        shared_actions=len(actions),action_selections=len(selectors),selection_width=2,
        encoding="six-bit base36 digits in flat natural-number blocks",
        samples=[dict(rank=r,active=c,index=i) for (r,c),i in sorted(samples.items())],
        source_bytes=args.output.stat().st_size,source_data_sha256=hashlib.sha256(args.output.read_bytes()).hexdigest(),
        seconds=round(time.monotonic()-started,3))
    args.report.write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps(report),flush=True)


def generate_checks(directory):
    base = directory
    common='''import MettapediaFourColor.WheelRepairCertificate

/-! # Finite block indices for complete wheel repair checks -/
namespace FourColor.WheelRepairCertificate

def checkAt (n : ℕ) : Bool :=
  check ⟨n % WheelRepairData.count, Nat.mod_lt _ (by decide)⟩
def inputAt (n : ℕ) : Bool := inputCheck (n % (3 ^ 12))

end FourColor.WheelRepairCertificate
'''
    (base/'WheelRepairCheckCommon.lean').write_text(common)
    for kind,checker,width,count in [('Record','checkAt',32,66430),('Input','inputAt',256,3**12)]:
        total=math.ceil(count/width)
        for shard,start in enumerate(range(0,total,128)):
            size=min(128,total-start)
            text='''import MettapediaFourColor.WheelRepairCheckCommon

/-! # Bounded kernel checks for the complete D3009 certificate

Generated by tools/fourcolor/near-linear/generate_wheel_repair.py.
Each finite block is checked by kernel reduction; no generator result is a premise.
-/
namespace FourColor.WheelRepairCertificate

set_option maxRecDepth 65536

'''
            for b in range(start,start+size):
                text+=f'''set_option maxHeartbeats 4000000 in
-- Validate one bounded block of the complete finite certificate.
theorem {kind.lower()}Block{b} : ∀ j : Fin {width},
    {checker} ({width*b} + j.val) = true := by decide +kernel

'''
            text+=f'''theorem {kind.lower()}Shard{shard} (b : Fin {size}) (j : Fin {width}) :
    {checker} ({width} * ({start} + b.val) + j.val) = true := by
  fin_cases b
'''
            for b in range(start,start+size):text+=f'  · exact {kind.lower()}Block{b} j\n'
            text+='\nend FourColor.WheelRepairCertificate\n'
            (base/f'WheelRepair{kind}{shard}.lean').write_text(text)
    text=''.join(f'import MettapediaFourColor.WheelRepair{kind}{s}\n' for kind in ['Record','Input'] for s in range(17))
    text+='''
/-! # Complete thirteen-port repair from checked finite data

Every supplied repair record and every proper input trace is checked. This
proves the finite D3009 repair contract. Ambient embedding, initial colouring
and strict reduction are separate geometric consumers.
-/
namespace FourColor.WheelRepairCertificate

set_option maxRecDepth 65536

'''
    for kind,checker,width in [('record','checkAt',32),('input','inputAt',256)]:
        text+=f'set_option maxHeartbeats 4000000 in\n-- Join the bounded shard proofs without rechecking their finite records.\ntheorem {kind}Blocks (b : Fin 2076) (j : Fin {width}) :\n    {checker} ({width} * b.val + j.val) = true := by\n  have hb := b.isLt\n'
        for shard in range(16):
            start=128*shard
            text+=f'  by_cases h{shard} : b.val < {start+128}\n'
            if shard==0:text+=f'  · simpa only [Nat.zero_add] using {kind}Shard0 ⟨b.val, h0⟩ j\n'
            else:
                text+=f'  · have h := {kind}Shard{shard} ⟨b.val - {start}, by omega⟩ j\n'
                text+=f'    have he : {start} + (b.val - {start}) = b.val := by omega\n'
                text+='    simpa only [he] using h\n'
        text+=f'  have h := {kind}Shard16 ⟨b.val - 2048, by omega⟩ j\n'
        text+='  have he : 2048 + (b.val - 2048) = b.val := by omega\n  simpa only [he] using h\n\n'
    text+='''set_option maxHeartbeats 4000000 in
-- Convert the bounded blocks into complete state coverage.
theorem checked (i : State) : check i = true := by
  have hi : i.val < 66430 := i.isLt
  have h := recordBlocks ⟨i.val / 32, by omega⟩ ⟨i.val % 32, Nat.mod_lt _ (by decide)⟩
  change checkAt (32 * (i.val / 32) + i.val % 32) = true at h
  have hn : 32 * (i.val / 32) + i.val % 32 = i.val := by omega
  simpa only [hn, checkAt, Nat.mod_eq_of_lt i.isLt] using h

set_option maxHeartbeats 4000000 in
-- Convert the bounded blocks into complete input coverage.
theorem coverage (i : Fin (3 ^ 12)) : inputCheck i = true := by
  have hi : i.val < 531441 := i.isLt
  have h := inputBlocks ⟨i.val / 256, by omega⟩ ⟨i.val % 256, Nat.mod_lt _ (by decide)⟩
  change inputAt (256 * (i.val / 256) + i.val % 256) = true at h
  have hn : 256 * (i.val / 256) + i.val % 256 = i.val := by omega
  simpa only [hn, inputAt, Nat.mod_eq_of_lt i.isLt] using h

/-- Every proper thirteen-port trace admits a compatible D3009 repair. -/
theorem repair : KempeBoundarySplit.Repairs Supports 13 := repair_of_checks checked coverage

end FourColor.WheelRepairCertificate
'''
    (base/'WheelRepairChecked.lean').write_text(text)


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--cache',type=Path)
    p.add_argument('--output',type=Path,required=True)
    p.add_argument('--report',type=Path,required=True)
    p.add_argument('--block',type=int,default=32)
    p.add_argument('--checks-dir',type=Path)
    args=p.parse_args()
    if args.block <= 0:p.error('--block must be positive')
    generate(args)
    if args.checks_dir:
        generate_checks(args.checks_dir)

if __name__=='__main__':
    main()
