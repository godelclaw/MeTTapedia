#!/usr/bin/env python3
"""Encode the retained exterior rotation and a spanning tour for Lean.

The output contains geometry, not colouring-repair witnesses. Row bytes are
decoded and their complete adjacency is verified by the consuming Lean file.
"""
import argparse
from hashlib import sha256
import json
from pathlib import Path

from audit_component_detach import chain
from audit_planar_exterior_disk import verify
from probe_flat_pairs import geometry


def generate(here):
    report = verify(here)
    source = here / 'component-detach-example.json'
    fixture = json.loads(source.read_text())
    _, ambient, nxt, _ = geometry(fixture['faces'])
    removed = set(fixture['images'][11:])
    carrier = sorted(set(ambient) - removed)
    label = {v: i for i, v in enumerate(carrier)}
    exterior = {v: ambient[v] - removed for v in carrier}
    codes = []
    for v in carrier:
        start = min(exterior[v])
        row, w = [], start
        while True:
            row.append(label[w])
            w = nxt[v, w]
            while w in removed:
                w = nxt[v, w]
            if w == start:
                break
        assert len(row) == len(exterior[v]) and len(row) < 256
        codes.append(len(row) + sum(u << (8*(i+1)) for i, u in enumerate(row)))
    tour = [label[v] for v in chain(exterior, set(carrier), carrier[0])]
    assert len(codes) == report['vertices'] == 155
    return f'''import Mettapedia.GraphTheory.FourColor.ComponentDetachExample

/-!
# Compact rotation input for the retained punctured graph

Generated by `generate_exterior_disk_data.py` from
`component-detach-example.json`, SHA-256
`{sha256(source.read_bytes()).hexdigest()}`.
The low byte is the row length; subsequent bytes are consecutive neighbour
labels. The spanning tour certifies connectedness. All graph and geometry
claims are proved separately by the consumer.
-/

namespace FourColor.ResidualExteriorDisk

set_option linter.style.longLine false in
def rowCodes : List Nat := {codes}

def rowCode (v : Fin 155) : Nat := rowCodes.get ⟨v.val, v.isLt⟩

def star (v : Fin 155) : List (Fin 155) :=
  (List.range (rowCode v % 256)).map fun i =>
    ⟨((rowCode v >>> (8 * (i + 1))) % 256) % 155, Nat.mod_lt _ (by decide)⟩

set_option linter.style.longLine false in
def tour : List (Fin 155) := {tour}

end FourColor.ResidualExteriorDisk
'''


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path)
    args = parser.parse_args()
    text = generate(Path(__file__).resolve().parent)
    if args.output:
        args.output.write_text(text)
    else:
        print(text, end='')
