#!/usr/bin/env python3
"""Emit flat data for the first exact mesh-region ordering obstruction.

Ranked spanning trees and edge closure identify every complete retained
component. No colouring data or configuration-reducibility certificates
are generated. The handwritten Lean consumer proves the physical cut bound.
"""

import argparse
import itertools
import json
from collections import deque
from pathlib import Path

from v24_contour_mesh_gate import verify_archive
from v24_mesh_region_order_gate import bits, flood, members


def build():
    archive = json.loads(Path('results/fourcolor/v24_contour_mesh_gate.json').read_text())
    regions = json.loads(Path('results/fourcolor/v24_mesh_region_gate.json').read_text())
    orders = json.loads(Path('results/fourcolor/v24_mesh_region_order_gate.json').read_text())
    verify_archive(archive)
    original, region = archive['receipts'][2], regions['receipts'][2]
    band, optimum = region['bands'][3], orders['receipts'][2]['bands'][3]
    graph = original['graph']
    assert original['frequency'] == region['frequency'] == orders['receipts'][2]['frequency'] == 3
    assert optimum['cell_ids'] == band['cells']
    assert optimum['anchor'] == band['anchor'] and optimum['rows'] == band['rows'] == [3, 4]
    edges, faces = graph['primal_edges'], graph['face_cycles']
    assert len(edges) == 270 and graph['primal_vertex_count'] == 180
    assert len(band['cells']) == 8 and optimum['candidate_bound'] == 15 and optimum['optimum'] == 16
    cells = [bits(v for f in region['cells'][i]['faces'] for v in faces[f]) for i in band['cells']]
    sixes = sorted(bits(s) for s in itertools.combinations(range(8), 6))
    optimal = [s['state'] for s in optimum['optimum_path']]
    states = sorted(set(sixes + [1 << i for i in range(8)] + [255] + optimal))
    adj, adj_edges = [0] * 180, [[] for _ in range(180)]
    for i, (u, v) in enumerate(edges):
        adj[u] |= 1 << v
        adj[v] |= 1 << u
        adj_edges[u].append((v, i))
        adj_edges[v].append((u, i))
    anchor, universe = band['anchor'], (1 << 180) - 1
    raw, components, parents, ranks = [], [], [], []
    for state in states:
        mask = 0
        for i in members(state):
            mask |= cells[i]
        component = flood(adj, universe ^ mask, anchor)
        rank, parent, seen = [0] * 180, [0] * 180, {anchor}
        queue = deque([anchor])
        while queue:
            u = queue.popleft()
            for v, edge in sorted(adj_edges[u]):
                if component & (1 << v) and v not in seen:
                    seen.add(v)
                    rank[v], parent[v] = rank[u] + 1, edge
                    queue.append(v)
        assert bits(seen) == component
        raw.append(mask)
        components.append(component)
        parents.extend(parent)
        ranks.extend(rank)
    return dict(edgeNumbers=[x for e in edges for x in e], cellMasks=cells,
                stateMasks=states, rawMasks=raw, componentMasks=components,
                parentNumbers=parents, rankNumbers=ranks,
                sixIndices=[states.index(s) for s in sixes],
                singletonIndices=[states.index(1 << i) for i in range(8)],
                optimalIndices=[states.index(s) for s in optimal]), anchor, states.index(255)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    tables, anchor, full = build()
    text = '''import Mathlib.Data.Finset.Powerset
import Mathlib.Data.Nat.Bitwise

/-!
# Flat data for the GP(3,0) region-ordering obstruction

Generated by `v24_mesh_region_order_witness.py` from the archived ambient
graph and its selected band. The consumer checks the ranked components
against every ambient edge; the component masks are not trusted floods.
-/

namespace Mettapedia.GraphTheory.FourColor.MeshRegionOrderData

set_option maxRecDepth 100000

def readLE (pages : Nat → ByteArray) (offset : Nat) : Nat → Nat
  | 0 => 0
  | n + 1 => readLE pages offset n +
      (pages ((offset + n) / 256))[(offset + n) % 256]!.toNat * 256 ^ n

structure Table where
  pages : Nat → ByteArray
  stride : Nat
  size : Nat

def Table.getD (t : Table) (i fallback : Nat) : Nat :=
  if i < t.size then readLE t.pages (i * t.stride) t.stride else fallback

theorem readLE_example : readLE (fun _ => ⟨#[23, 1]⟩) 0 2 = 279 := by decide +kernel

'''
    for name, numbers in tables.items():
        stride = max(1, (max(numbers).bit_length() + 7) // 8)
        packed = b''.join(n.to_bytes(stride, 'little') for n in numbers)
        assert [int.from_bytes(packed[i:i + stride], 'little')
                for i in range(0, len(packed), stride)] == numbers
        page_names = []
        for offset in range(0, len(packed), 256):
            page_name = f'{name}Page{offset // 256}'
            page_names.append(page_name)
            page = packed[offset:offset + 256]
            text += f'def {page_name} : ByteArray := ByteArray.mk #[\n'
            text += ',\n'.join('    ' + ', '.join(map(str, page[i:i + 32]))
                                for i in range(0, len(page), 32)) + '\n  ]\n\n'
        text += f'def {name} : Table where\n  stride := {stride}\n  size := {len(numbers)}\n'
        text += '  pages := fun p => match p with\n'
        text += ''.join(f'    | {i} => {page_name}\n' for i, page_name in enumerate(page_names))
        text += '    | _ => ByteArray.empty\n\n'
    text += f'def anchor : Fin 180 := {anchor}\n'
    text += f'abbrev Cases := Fin {len(tables["stateMasks"])}\n'
    text += f'def fullIndex : Cases := {full}\n\n'
    text += 'end Mettapedia.GraphTheory.FourColor.MeshRegionOrderData\n'
    target = Path('lean/mettapedia/Mettapedia/GraphTheory/FourColor/MeshRegionOrderData.lean')
    if args.check:
        assert target.read_text() == text
    else:
        target.write_text(text)
    print(f'Emitted {len(tables["stateMasks"])} component witnesses, {len(text)} characters')
    count = len(tables['stateMasks'])
    chunk_size = 7
    imports = []
    for start in range(0, count, chunk_size):
        name = f'MeshRegionOrderChecks{start // chunk_size}'
        imports.append(f'import Mettapedia.GraphTheory.FourColor.{name}')
        source = ('import Mettapedia.GraphTheory.FourColor.MeshRegionOrderCheckCore\n\n'
                  '/-! Kernel checks of complete ranked components and full cuts. -/\n\n'
                  'namespace Mettapedia.GraphTheory.FourColor.MeshRegionOrderObstruction\n'
                  'set_option maxRecDepth 100000\n\n')
        for t in range(start, min(start + chunk_size, count)):
            source += f'theorem case_checked_{t} : caseCheck {t} = true := by decide +kernel\n'
        source += '\nend Mettapedia.GraphTheory.FourColor.MeshRegionOrderObstruction\n'
        path = target.with_name(name + '.lean')
        if args.check:
            assert path.read_text() == source
        else:
            path.write_text(source)
    source = '\n'.join(imports) + ('\nimport Mathlib.Tactic.FinCases\n\n'
              '/-! Assembly of the individually checked component witnesses. -/\n\n'
              'namespace Mettapedia.GraphTheory.FourColor.MeshRegionOrderObstruction\n'
              'open MeshRegionOrderData\n\n'
              'theorem cases_checked : ∀ t : Cases, caseCheck t = true := by\n'
              '  intro t\n  fin_cases t\n')
    source += ''.join(f'  · exact case_checked_{t}\n' for t in range(count))
    source += '\nend Mettapedia.GraphTheory.FourColor.MeshRegionOrderObstruction\n'
    path = target.with_name('MeshRegionOrderChecks.lean')
    if args.check:
        assert path.read_text() == source
    else:
        path.write_text(source)
